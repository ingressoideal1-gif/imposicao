const fs = require('node:fs');
const assert = require('node:assert/strict');
const { PGlite } = require(process.env.PGLITE_MODULE || '@electric-sql/pglite');
(async () => {
 const db = new PGlite();
 await db.exec('CREATE TABLE pedidos_modelos(id integer primary key, status_impressao text, acabamento_status text, nota text); INSERT INTO pedidos_modelos VALUES(1, \'Aguardando\', NULL, \'antigo\');');
 await db.exec(fs.readFileSync('sql/data_hora_status_paineis.sql','utf8'));
 const row = async () => (await db.query('SELECT * FROM pedidos_modelos WHERE id=1')).rows[0];
 assert.equal((await row()).status_impressao_registrado_em, null);
 assert.equal((await row()).acabamento_status_registrado_em, null);
 await db.exec("UPDATE pedidos_modelos SET status_impressao='Impresso' WHERE id=1");
 const impresso = await row();
 assert(impresso.status_impressao_registrado_em);
 assert.equal(+impresso.status_impressao_registrado_em, +impresso.acabamento_status_registrado_em);
 await db.exec("UPDATE pedidos_modelos SET nota='outra', status_impressao='Impresso' WHERE id=1");
 assert.equal(+(await row()).status_impressao_registrado_em, +impresso.status_impressao_registrado_em);
 await db.exec("UPDATE pedidos_modelos SET acabamento_status='Pronto' WHERE id=1");
 const pronto = await row();
 assert.equal(+pronto.status_impressao_registrado_em, +impresso.status_impressao_registrado_em);
 assert(pronto.acabamento_status_registrado_em);
 await db.exec("UPDATE pedidos_modelos SET status_impressao='Corrigir Arte' WHERE id=1");
 assert.equal(+(await row()).acabamento_status_registrado_em, +pronto.acabamento_status_registrado_em);
 await db.exec("UPDATE pedidos_modelos SET acabamento_status=NULL WHERE id=1");
 assert((await row()).acabamento_status_registrado_em);
 const antes = await row();
 await db.exec("UPDATE pedidos_modelos SET status_impressao_registrado_em='2000-01-01', acabamento_status_registrado_em='2000-01-01' WHERE id=1");
 assert.equal(+(await row()).status_impressao_registrado_em, +antes.status_impressao_registrado_em);
 assert.equal(+(await row()).acabamento_status_registrado_em, +antes.acabamento_status_registrado_em);
 await db.exec("INSERT INTO pedidos_modelos(id,status_impressao) VALUES(2,'Aguardando')");
 const novo=(await db.query('SELECT * FROM pedidos_modelos WHERE id=2')).rows[0];
 assert(novo.status_impressao_registrado_em && novo.acabamento_status_registrado_em);
 await db.close();
 console.log('OK: PostgreSQL local - migracao, legado, transicoes, repeticao, campos independentes e carimbos protegidos.');
})().catch(e=>{console.error(e);process.exitCode=1;});
